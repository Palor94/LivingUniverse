// Messages built from a fixed start and a name (2026-11-11): [English pattern, Hungarian with $1].
export const serverPatterns=[
  [/^The conversation with (.*) could not be saved \((.*)\)\. Try again\.$/,'A beszélgetést ($1) nem sikerült elmenteni ($2). Próbáld újra.'],
  [/^The picture could not be moved \((.*)\)\. Nothing was changed\.$/,'A képet nem sikerült áthelyezni ($1). Semmi nem változott.'],
  [/^No usable image in (.*)\. Figure generation from text alone is disabled\.$/,'Nincs használható kép ebben a karaktermappában: $1. Kép nélkül nem készül figura.'],
  [/^The car is not here: it is at (.*)\.$/,'Az autó nincs itt, hanem itt áll: $1.'],
  [/^Work is in progress \((.*)\)\. Restart when it has finished\.$/,'Munka folyik ($1). Várd meg a végét, utána indítsd újra.'],
  [/^Several characters have the name (.*)\. Choose the intended character in the folder options\.$/,'Több szereplőnek is ez a neve: $1. Válaszd ki a mappa beállításainál, melyikről van szó.']
];
// Hungarian version of a server message, or the original when none is known.
export function translateServerMessage(message){
  if(serverMessages[message]!==undefined)return serverMessages[message];
  for(const [pattern,hu] of serverPatterns)if(pattern.test(message))return message.replace(pattern,hu);
  return message;
}

// Returns the text for `key` with {placeholders} filled in. A missing key returns the
// key itself (and warns), so a forgotten translation is visible instead of blank.
export function t(key,vars={}){
  const text=hu[key];
  if(text===undefined){console.warn('Missing text:',key);return key;}
  return text.replace(/\{(\w+)\}/g,(match,name)=>name in vars?String(vars[name]):match);
}

// Fills static markup: <span data-i18n="key"> gets textContent, and
// data-i18n-attr="attribute:key" sets an attribute (e.g. aria-label, placeholder).
export function translateDocument(root=document){
  for(const el of root.querySelectorAll('[data-i18n]'))el.textContent=t(el.dataset.i18n);
  for(const el of root.querySelectorAll('[data-i18n-attr]')){const [attr,key]=el.dataset.i18nAttr.split(':');el.setAttribute(attr,t(key));}
}
